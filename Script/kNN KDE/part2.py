def add_bounding_box(fig_obj, b_min=0, b_max=120, color='gray', width=2):
    """Adds a 3D bounding box to a Plotly figure."""
    x_coords, y_coords, z_coords = [], [], []
    edges = [
        ([b_min, b_max], [b_min, b_min], [b_min, b_min]), ([b_max, b_max], [b_min, b_max], [b_min, b_min]),
        ([b_max, b_min], [b_max, b_max], [b_min, b_min]), ([b_min, b_min], [b_max, b_min], [b_min, b_min]),
        ([b_min, b_max], [b_min, b_min], [b_max, b_max]), ([b_max, b_max], [b_min, b_max], [b_max, b_max]),
        ([b_max, b_min], [b_max, b_max], [b_max, b_max]), ([b_min, b_min], [b_max, b_min], [b_max, b_max]),
        ([b_min, b_min], [b_min, b_min], [b_min, b_max]), ([b_max, b_max], [b_min, b_min], [b_min, b_max]),
        ([b_min, b_min], [b_max, b_max], [b_min, b_max]), ([b_max, b_max], [b_max, b_max], [b_min, b_max])
    ]
    for ex, ey, ez in edges:
        x_coords.extend(list(ex) + [None]); y_coords.extend(list(ey) + [None]); z_coords.extend(list(ez) + [None])
    fig_obj.add_trace(go.Scatter3d(
        x=x_coords, y=y_coords, z=z_coords, mode='lines',
        line=dict(color=color, width=width), name='_bounding_box', showlegend=False))
    return fig_obj

def find_3d_peaks_from_density(density_matrix_3d, grid_coords_1d, current_grid_vox_size, min_dist_physical_nm_val, threshold_rel_val_param):
    """Finds local maxima (peaks) in a 3D density matrix."""
    calculated_min_dist_vox = max(1, int(round(min_dist_physical_nm_val / current_grid_vox_size)))
    print(f"\nInitiating 3D peak finding in KDE volume...")
    print(f"  Density matrix shape: {density_matrix_3d.shape}")
    print(f"  Physical min peak dist: {min_dist_physical_nm_val:.2f} nm, Voxel size: {current_grid_vox_size} nm")
    print(f"  Calculated min dist (voxels): {calculated_min_dist_vox}, Relative threshold: {threshold_rel_val_param}")

    peak_indices_voxel = peak_local_max(
        density_matrix_3d, min_distance=calculated_min_dist_vox, threshold_rel=threshold_rel_val_param)
    num_peaks_found = peak_indices_voxel.shape[0]
    print(f"  Found {num_peaks_found} peaks in 3D KDE volume.")

    peaks_nm_coordinates_list = []
    if num_peaks_found > 0:
        for i in range(num_peaks_found):
            z_idx, y_idx, x_idx = peak_indices_voxel[i]
            peaks_nm_coordinates_list.append((grid_coords_1d[x_idx], grid_coords_1d[y_idx], grid_coords_1d[z_idx]))
    return peaks_nm_coordinates_list

def proj_xy(density_map, z_center_nm, thick_nm, current_grid_vox_size):
    """Calculates an XY projection from a 3D density map by averaging."""
    half_thick = thick_nm / 2
    lo_idx = int(max(0,  z_center_nm - half_thick) / current_grid_vox_size)
    hi_idx = int(min(120, z_center_nm + half_thick) / current_grid_vox_size)
    lo_idx = max(0, min(lo_idx, density_map.shape[0] -1))
    hi_idx = max(0, min(hi_idx, density_map.shape[0] -1))
    if lo_idx > hi_idx :
        return np.zeros((density_map.shape[1], density_map.shape[2]), dtype=density_map.dtype)
    return density_map[lo_idx:hi_idx+1].mean(axis=0)

def generate_z_level_guide_images(fig_volume, z_levels, prefix, output_dir):
    """Generates clean, Y-view static images of the 3D volume with a guide plane at specified Z-levels."""
    print("\nGenerating Z-level guide images...")
    guide_img_dir = os.path.join(output_dir, "Z_Level_Guides")
    os.makedirs(guide_img_dir, exist_ok=True)

    # Define camera for Y-view
    cam_dist = 2.5 * 1.2
    eye_cam = dict(x=0, y=cam_dist, z=0)
    cam_settings = dict(eye=eye_cam, up=dict(x=0, y=0, z=1), center=dict(x=0, y=0, z=0))

    # Define the plane coordinates
    x_plane_surface = [0, 120, 120, 0]
    y_plane_surface = [0, 0, 120, 120]

    # Define border line coordinates
    x_plane_border = [0, 120, 120, 0, 0]
    y_plane_border = [0, 0, 120, 120, 0]

    for z_level in z_levels:
        fig_guide = copy.deepcopy(fig_volume)

        # Add a semi-transparent grey plane at the current Z-level
        fig_guide.add_trace(go.Mesh3d(
            x=x_plane_surface,
            y=y_plane_surface,
            z=[z_level, z_level, z_level, z_level],
            color='grey',
            opacity=0.5,
            name=f'Z={z_level} Plane'
        ))

        # Add a black border around the plane
        fig_guide.add_trace(go.Scatter3d(
            x=x_plane_border,
            y=y_plane_border,
            z=[z_level, z_level, z_level, z_level, z_level],
            mode='lines',
            line=dict(color='black', width=3),
            showlegend=False
        ))


        # Clean up the layout for a minimal visual guide
        fig_guide.update_layout(
            title_text="",
            showlegend=False,
            scene_camera=cam_settings,
            scene=dict(
                xaxis=dict(visible=False),
                yaxis=dict(visible=False),
                zaxis=dict(visible=False),
            )
        )

        # Hide the color bar of the volume plot
        if fig_guide.data and hasattr(fig_guide.data[0], 'colorbar'):
            fig_guide.data[0].showscale = False

        snap_path = os.path.join(guide_img_dir, f"{prefix}_Z_guide_{z_level:03d}.png")
        print(f"  Writing Z-level guide for Z={z_level} to: {snap_path}")
        try:
            fig_guide.write_image(
                str(snap_path),
                width=snapshot_output_width,
                height=snapshot_output_height,
                scale=SNAPSHOT_DPI / 96.0
            )
        except Exception as e:
            print(f"    Error writing Z-level guide snapshot {snap_path}: {e}")

